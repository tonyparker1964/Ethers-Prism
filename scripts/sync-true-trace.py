#!/usr/bin/env python3
"""Builds the Blender scripts into the app: True Trace (Tools/true-trace) and Sculpt 3D (Tools/sculpt-3d).

Run after editing any of their core.py or build.py:  python3 scripts/sync-true-trace.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent

for folder, owner, header, out in [
    ("true-trace", "TrueTrace", "True Trace: rebuilds a picture from Grease Pencil shapes and ink in a chosen look.", "TrueTraceScript.swift"),
    ("sculpt-3d", "Sculpt3D", "Sculpt 3D: turns a picture into a rounded 3D model in a chosen 3D look.", "Sculpt3DScript.swift"),
]:
    tools = root / "Tools" / folder
    core = (tools / "core.py").read_text(encoding="utf-8").split('"""', 2)[2].lstrip("\n")
    build = (tools / "build.py").read_text(encoding="utf-8")
    script = f"# Ethers Prism · {header}\n" + core + build
    assert '"""###' not in script
    swift = (
        f"// Generated by scripts/sync-true-trace.py from Tools/{folder}. Don't edit by hand.\n\n"
        f"extension {owner} {{\n"
        "    /// Runs inside Blender (background). Arguments arrive as JSON after `--`.\n"
        '    static let script = ###"""\n' + script.rstrip("\n") + '\n"""###\n'
        "}\n"
    )
    (root / "Sources/EthersPrismCore/Adapters" / out).write_text(swift, encoding="utf-8")
    print("Updated", out)

#!/usr/bin/env python3
"""Builds the True Trace Blender script into the app from Tools/true-trace/core.py + build.py.

Run after editing either file:  python3 scripts/sync-true-trace.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
tools = root / "Tools/true-trace"
core = (tools / "core.py").read_text(encoding="utf-8").split('"""', 2)[2].lstrip("\n")
build = (tools / "build.py").read_text(encoding="utf-8")
script = "# Ethers Prism · True Trace: rebuilds a picture from Grease Pencil shapes and ink in a chosen look.\n" + core + build
assert '"""###' not in script
swift = (
    "// Generated by scripts/sync-true-trace.py from Tools/true-trace. Don't edit by hand.\n\n"
    "extension TrueTrace {\n"
    "    /// Runs inside Blender (background). Arguments arrive as JSON after `--`.\n"
    '    static let script = ###"""\n' + script.rstrip("\n") + '\n"""###\n'
    "}\n"
)
(root / "Sources/EthersPrismCore/Adapters/TrueTraceScript.swift").write_text(swift, encoding="utf-8")
print("Updated TrueTraceScript.swift")
